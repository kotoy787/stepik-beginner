from random import choice

answers = [
    # Положительные
    "Бесспорно",
    "Предрешено",
    "Никаких сомнений",
    "Определённо да",
    "Можешь быть уверен в этом",
    "Мне кажется — да",
    "Вероятнее всего",
    "Хорошие перспективы",
    "Знаки говорят — да",
    "Да",
    # Нейтральные (неопределённые)
    "Пока не ясно, попробуй снова",
    "Спроси позже",
    "Лучше не рассказывать",
    "Сейчас нельзя предсказать",
    "Сконцентрируйся и спроси опять",
    # Отрицательные
    "Даже не думай",
    "Мой ответ — нет",
    "По моим данным — нет",
    "Перспективы не очень хорошие",
    "Весьма сомнительно",
]

print("Привет Мир, я магический шар, и я знаю ответ на любой твой вопрос.")

name = input("Как вас зовут? ").strip()
print(f"Привет, {name}! Задавай вопрос, а я на него отвечу.\n")

while True:
    question = input("Твой вопрос: ")

    # Проверка, чтобы не отвечал на пустую строку
    if not question.strip():
        print("Ты ничего не спросил. Попробуй ещё раз.")
        continue

    print(choice(answers))

    again = input("\nХочешь задать еще вопрос? (д/н): ").strip().lower()
    if again not in ("д", "да", "y", "yes"):
        print(f"Возвращайся, если возникнут вопросы, {name}!")
        break

    print("-" * 30)