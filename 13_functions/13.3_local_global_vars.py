# 13.3 Локальные и глобальные переменные (Теория)

# Локальные переменные: живут только внутри функции.
# "Что происходит в Вегасе, остается в Вегасе"

def my_func():
    local_var = 10  # Локальная переменная
    # Она существует только здесь, внутри функции

# Если раскомментировать строку ниже, будет ошибка NameError,
# потому что снаружи local_var не существует.
# print(local_var) 

# Глобальные переменные: объявлены вне функции, видны везде.
global_var = 5

def change_global():
    global global_var  # Объявляем, что хотим изменить глобальную
    global_var = 20

# Правило: global объявляется в начале функции, до использования переменной.
# В реальном коде global используют редко (лучше через return).